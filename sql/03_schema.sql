-- PostgreSQL 16+. Run through python -m backend.manage init.
CREATE TABLE IF NOT EXISTS users (
 user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL UNIQUE CHECK (email = lower(email) AND email ~ '^[^ @]+@[^ @]+[.][^ @]+$'),
 display_name TEXT NOT NULL CHECK (length(trim(display_name)) BETWEEN 1 AND 100),
 password_hash TEXT NOT NULL CHECK (password_hash LIKE 'scrypt$%'),
 role TEXT NOT NULL CHECK (role IN ('admin','analyst')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY CHECK (length(token_hash)=64),
 user_id BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS companies (
 company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_name TEXT NOT NULL CHECK (length(trim(company_name)) BETWEEN 1 AND 150),
 ticker TEXT NOT NULL UNIQUE CHECK (ticker ~ '^[A-Z0-9.-]{1,15}$'),
 sector TEXT NOT NULL CHECK (length(trim(sector)) BETWEEN 1 AND 100)
);
CREATE TABLE IF NOT EXISTS models (
 model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 model_name TEXT NOT NULL CHECK (length(trim(model_name))>0),
 version TEXT NOT NULL CHECK (length(trim(version))>0),
 UNIQUE(model_name,version)
);
CREATE TABLE IF NOT EXISTS news (
 news_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 headline TEXT NOT NULL CHECK (length(trim(headline)) BETWEEN 1 AND 300),
 news_text TEXT NOT NULL CHECK (length(trim(news_text)) BETWEEN 1 AND 12000),
 published_at DATE NOT NULL,
 source TEXT NOT NULL DEFAULT 'Demo / simulated' CHECK (length(trim(source))>0)
);
CREATE TABLE IF NOT EXISTS investments (
 investment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies,
 model_id BIGINT NOT NULL REFERENCES models,
 investment_amount NUMERIC(16,2) NOT NULL CHECK (investment_amount>0 AND investment_amount<100000000000000),
 decision TEXT NOT NULL CHECK (decision IN ('BUY','SELL','HOLD')),
 trade_date DATE NOT NULL,
 return_percentage NUMERIC(10,4) CHECK (return_percentage BETWEEN -100 AND 100000)
);
CREATE TABLE IF NOT EXISTS investment_reasoning (
 reasoning_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 investment_id BIGINT NOT NULL REFERENCES investments ON DELETE CASCADE,
 news_id BIGINT NOT NULL REFERENCES news,
 reasoning_text TEXT NOT NULL CHECK (length(trim(reasoning_text)) BETWEEN 1 AND 12000),
 confidence NUMERIC(5,4) NOT NULL CHECK (confidence BETWEEN 0 AND 1),
 vector_memory_id TEXT NOT NULL UNIQUE DEFAULT ('memory_' || gen_random_uuid()::text)
);
-- A real additive migration demonstrates ALTER without dropping stored memories.
ALTER TABLE investments ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES users;
ALTER TABLE investments ADD COLUMN IF NOT EXISTS revision INTEGER NOT NULL DEFAULT 1 CHECK (revision>0);
CREATE INDEX IF NOT EXISTS idx_investments_company ON investments(company_id);
CREATE INDEX IF NOT EXISTS idx_investments_model ON investments(model_id);
CREATE INDEX IF NOT EXISTS idx_reasoning_investment ON investment_reasoning(investment_id);
CREATE INDEX IF NOT EXISTS idx_reasoning_news ON investment_reasoning(news_id);
CREATE INDEX IF NOT EXISTS idx_companies_sector ON companies(sector);
CREATE TABLE IF NOT EXISTS audit_log (
 audit_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 table_name TEXT NOT NULL,
 record_id BIGINT NOT NULL,
 operation TEXT NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
 actor_id BIGINT REFERENCES users,
 old_data JSONB,
 new_data JSONB,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION audit_investment_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO audit_log(table_name,record_id,operation,actor_id,old_data,new_data)
 VALUES (TG_TABLE_NAME, COALESCE(NEW.investment_id,OLD.investment_id), TG_OP,
 NULLIF(current_setting('app.actor_id',true),'')::bigint,
 CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD) END,
 CASE WHEN TG_OP='DELETE' THEN NULL ELSE to_jsonb(NEW) END);
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END; $$;
CREATE OR REPLACE TRIGGER investment_audit AFTER INSERT OR UPDATE OR DELETE ON investments
 FOR EACH ROW EXECUTE FUNCTION audit_investment_change();
CREATE OR REPLACE VIEW memory_details AS
 SELECT r.*,i.company_id,i.model_id,i.investment_amount,i.decision,i.trade_date,
 i.return_percentage,i.created_by,i.revision,c.company_name,c.ticker,c.sector,
 m.model_name,m.version,n.headline,n.news_text,n.published_at,n.source
 FROM investment_reasoning r JOIN investments i USING(investment_id)
 JOIN companies c USING(company_id) JOIN models m USING(model_id) JOIN news n USING(news_id);
CREATE OR REPLACE VIEW company_performance AS
 SELECT c.company_id,c.company_name,c.sector,COUNT(i.investment_id) AS investment_count,
 ROUND(AVG(i.return_percentage),2) AS average_return_pct,
 COALESCE(SUM(i.investment_amount),0) AS total_amount
 FROM companies c LEFT JOIN investments i USING(company_id)
 GROUP BY c.company_id,c.company_name,c.sector;
